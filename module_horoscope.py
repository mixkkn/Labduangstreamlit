def summarize_horoscope(score):
    """
    รับคะแนนดวงประจำวัน (จาก get_daily_score) แล้วคืนค่าข้อความสรุปภาพรวม
    โดยแบ่งเป็น 3 ระดับ: 8-10 = "ปังมาก", 4-7 = "เรื่อยๆ", 1-3 = "ต้องระวัง"

    Args:
        score (int): คะแนนดวงประจำวัน (1-10)

    Returns:
        str: ข้อความสรุปภาพรวมของดวงในวันนั้น
    """
    if score >= 8:
        return "ปังมาก"
    elif score >= 4:
        return "เรื่อยๆ"
    elif score >= 1:
        return "ต้องระวัง"
    else:
        return "ไม่สามารถประเมินได้ (คะแนนไม่ถูกต้อง)"