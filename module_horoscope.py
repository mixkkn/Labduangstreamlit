import random


def get_daily_score():
    """
    สุ่มคะแนนความดวงดีประจำวัน อยู่ในช่วง 1-10 คะแนน

    Returns:
        int: คะแนนดวงประจำวัน (1-10)
    """
    return random.randint(1, 10)


